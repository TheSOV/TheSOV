// Combining marks left over after NFD decomposition, drawn in the two rows above the letter.
export const MARKS = {
  "\u0301": G("...#. ..#.."), // acute
  "\u0303": G(".##.# #..#."), // tilde
  "\u0308": G("..... .#.#."), // diaeresis
};

function lookup(table, key, ch) {
  const rows = table[key];
  if (!rows) throw new Error(`no pixel glyph for "${ch}"`);
  return rows;
}

// A character becomes its letter rows plus the rows of any accent, offset to the line.
function glyphCells(ch) {
  const [base, ...marks] = ch.toUpperCase().normalize("NFD");
  const layers = [{ rows: lookup(GLYPHS, base, ch), top: ACCENT_ROWS }];
  for (const m of marks) layers.push({ rows: lookup(MARKS, m, ch), top: 0 });
  return layers;
}

export const textWidth = (text) => Math.max(0, [...text].length * ADVANCE - 1);

export function textGrid(text, colour) {
  const w = textWidth(text);
  const px = new Array(w * LINE_H).fill(null);
  [...text].forEach((ch, i) => {
    for (const { rows, top } of glyphCells(ch)) {
      rows.forEach((row, ry) => [...row].forEach((c, rx) => {
        if (c === "#") px[(top + ry) * w + i * ADVANCE + rx] = colour;
      }));
    }
  });
  return { w, h: LINE_H, px };
}

export const textSvg = (text, { x = 0, y = 0, scale = 1, colour }) =>
  placed({ x, y, scale }, pathsSvg(textGrid(text, colour)));
